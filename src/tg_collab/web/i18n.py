def t(key: str, lang: str = "en") -> str:
    """Translate a key; unknown keys fall back to English, then to the key itself."""
    table: dict[str, Any] = TRANSLATIONS.get(lang) or TRANSLATIONS["en"]
    if key in table:
        return str(table[key])
    return str(TRANSLATIONS["en"].get(key, key))


def label(group: str, value: str | None, lang: str = "en") -> str:
    """Human label for an enum value (``group_value`` keys).

    An unknown or future enum value falls back to the raw code instead of a
    missing-key marker, so a new provider or status never breaks the page.
    """
    if not value:
        return ""
    key = f"{group}_{value}"
    table = TRANSLATIONS.get(lang)
    if table is not None and key in table:
        return str(table[key])
    if key in TRANSLATIONS["en"]:
        return str(TRANSLATIONS["en"][key])
    return str(value)
